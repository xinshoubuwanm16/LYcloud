-- ============================================================
-- LY云计算 升级脚本：1.7.2 → 1.7.3
-- 内容：兑换码面额下限 1.00 → 0.01（支持 0.1 / 0.5 等小额兑换码）
--
-- 特点：幂等，可重复执行
--   · 仅当当前值仍是历史默认值 '1.00' 时才下调，避免覆盖管理员的自行设置
--   · 若该键不存在（老库结构差异）则补一条 0.01
--
-- 执行方式：
--   mysql -uroot -p 库名 < install/upgrade_1.7.3.sql
-- ============================================================

-- 1) 已在 schema 中且值仍为历史默认 1.00 → 下调为 0.01
UPDATE `ly_settings`
SET `v` = '0.01'
WHERE `k` = 'redeem_min_amount' AND `v` = '1.00';

-- 2) 键完全缺失 → 补默认值（INSERT IGNORE 不会覆盖已存在的行）
INSERT IGNORE INTO `ly_settings` (`k`, `v`) VALUES
('redeem_min_amount', '0.01');

-- 3) 结果回显（按数值判断：是否已能覆盖 0.1 / 0.5 这类小额）
SELECT CONCAT('升级完成：兑换码面额下限当前为 ¥', `v`,
              CASE WHEN `v` + 0 <= 0.01
                   THEN '，现在可生成 0.1 / 0.5 等小额兑换码'
                   ELSE CONCAT('（该值为您此前手动设置，未自动覆盖；若需 0.1 / 0.5 的小额码，',
                               '请将其调整为不大于 0.01）') END) AS result
FROM `ly_settings` WHERE `k` = 'redeem_min_amount';
